# 2.Comparison operators :

"""
1.Equals to [ == ] :
        1.Equals to operators are used to check whether LHS or RHS both are equals.
        2.It return True if both are equal or return False if both are not equals.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 == n2)

"""
2.Not Equals to [ != ] :
        1.Not Equals to operator are used to check whether LHS or RHS both are not equals.
        2.It return True if both are not equal or return False if both are equals.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 != n2)

"""
3.Greater than [ > ] :
        1.Greater than operator are used to check whether LHS is greater than RHS.
        2.It return True if LHS is greater than RHS otherwise it return False.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 > n2)

"""
4.Less than [ < ] :
        1.less than operator are used to check whether LHS is less than RHS.
        2.It return True if LHS is less than RHS otherwise it return False.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 < n2)

"""
5.Greater than Equals to [ >= ] :
        1.Greater than or equaals to operator are used to check whether LHS is greater than or equals to RHS.
        2.It return True if LHS is greater than or equals to RHS otherwise it return False.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 >= n2)

"""
6.Less than Equals to [ <= ] :
        1.Less than or equaals to operator are used to check whether LHS is less than or equals to RHS.
        2.It return True if LHS is less than or equals to RHS otherwise it return False.
"""

n1 = int(input("Enter first number : "))
n2 = int(input("Enter second number : "))
print(n1 <= n2)