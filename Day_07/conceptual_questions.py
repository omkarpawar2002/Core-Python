# When should you use a for loop instead of a while loop?
"""
1.when we know the exact number of time the iteration is required then we used for loop.
2.when we don't know the exact number of time the iteration is required then we used while loop.
"""

# What is the difference between break and continue?
"""
1.break keyword is used when we immediately want to exits from the loop.
2.continue keyword is used when we want to skip the current iteration and jump on the next iteration.
"""

# Why is the stop value excluded in range()?
"""
In Python, range() excludes the stop value because it follows the half-open interval [start, stop). 
This makes loops predictable, avoids off-by-one errors, and matches slicing behavior.
"""

# What is the purpose of the loop else block?
"""
1.loop else block we generally used when we want some condition check like found or not found like this.
2.else block in loop will get executed only if loop normally run successfully.
3.or if the loop break forcefully by using break keyword then else not run.
"""

